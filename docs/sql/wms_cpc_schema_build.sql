-- -----------------------------------------------------------------------------
-- 6. wms.receipt_items — roll_id BIGINT + FKs to fabric_rolls and boxes
-- -----------------------------------------------------------------------------
DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'wms' AND table_name = 'receipt_items'
      AND column_name = 'roll_id'
      AND data_type = 'integer'
  ) THEN
    ALTER TABLE wms.receipt_items
      ALTER COLUMN roll_id TYPE BIGINT USING roll_id::bigint;
  END IF;
END $$;

ALTER TABLE wms.receipt_items DROP CONSTRAINT IF EXISTS fk_receipt_items_roll;
ALTER TABLE wms.receipt_items DROP CONSTRAINT IF EXISTS fk_receipt_items_box;

ALTER TABLE wms.receipt_items
  ADD CONSTRAINT fk_receipt_items_roll
    FOREIGN KEY (roll_id) REFERENCES wms.fabric_rolls(id) ON UPDATE CASCADE ON DELETE SET NULL;

ALTER TABLE wms.receipt_items
  ADD CONSTRAINT fk_receipt_items_box
    FOREIGN KEY (box_id) REFERENCES wms.boxes(id) ON UPDATE CASCADE ON DELETE SET NULL;

