-- =============================================================================
-- wms-cpc: WMS-only DDL (shades, fabric_rolls, receipt location split, item FKs)
-- Aligns with backend/models.py. Does NOT create or alter core.* tables.
--
-- Prerequisites (must already exist):
--   - Schemas: core, wms
--   - core.clients(client_id), core.colors(color_id), core.materials(material_id)
--   - wms.warehouses, wms.warehouse_racks, wms.logical_locations, wms.boxes
--   - wms.receipts, wms.receipt_items
--
-- PostgreSQL 11+ recommended (ADD COLUMN IF NOT EXISTS).
-- Backup the database before running.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 0. Schemas (safe if already present)
-- -----------------------------------------------------------------------------
CREATE SCHEMA IF NOT EXISTS wms;

-- -----------------------------------------------------------------------------
-- 1. WMS enum types (idempotent — no-op if type already exists)
-- -----------------------------------------------------------------------------
DO $$ BEGIN
  CREATE TYPE wms.warehouse_type AS ENUM ('Fabric', 'RMG', 'Accessory');
EXCEPTION
  WHEN duplicate_object THEN NULL;
END $$;

DO $$ BEGIN
  CREATE TYPE wms.receipt_type AS ENUM ('inbound', 'dyehouse', 'internal', 'shipping');
EXCEPTION
  WHEN duplicate_object THEN NULL;
END $$;

DO $$ BEGIN
  CREATE TYPE wms.receipt_status AS ENUM ('issued', 'confirmed', 'cancelled');
EXCEPTION
  WHEN duplicate_object THEN NULL;
END $$;

DO $$ BEGIN
  CREATE TYPE wms.transaction_type AS ENUM ('IN', 'OUT');
EXCEPTION
  WHEN duplicate_object THEN NULL;
END $$;

DO $$ BEGIN
  CREATE TYPE wms.logical_location_type AS ENUM ('client', 'dyehouse', 'internal');
EXCEPTION
  WHEN duplicate_object THEN NULL;
END $$;

-- logical_locations table is a prerequisite; add Location Type when missing
ALTER TABLE wms.logical_locations
  ADD COLUMN IF NOT EXISTS location_type wms.logical_location_type NOT NULL DEFAULT 'internal';

-- -----------------------------------------------------------------------------
-- 2. wms.shades
--     FKs reference core.clients(client_id) and core.colors(color_id) — not "id".
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS wms.shades (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id INTEGER NOT NULL REFERENCES core.clients(client_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    color_id INTEGER NOT NULL REFERENCES core.colors(color_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    shade_number INTEGER NOT NULL,
    CONSTRAINT uq_wms_shades_client_color_number UNIQUE (client_id, color_id, shade_number),
    CONSTRAINT ck_wms_shades_positive_number CHECK (shade_number > 0)
);

CREATE INDEX IF NOT EXISTS ix_wms_shades_client_color ON wms.shades (client_id, color_id);

-- -----------------------------------------------------------------------------
-- 3. wms.fabric_rolls (requires wms.warehouse_racks and wms.shades)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS wms.fabric_rolls (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    roll_id VARCHAR(50) NOT NULL UNIQUE,
    barcode VARCHAR(100) UNIQUE,
    client_id INTEGER NOT NULL REFERENCES core.clients(client_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    color_id INTEGER REFERENCES core.colors(color_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    material_id INTEGER NOT NULL REFERENCES core.materials(material_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    lot_number VARCHAR(50),
    gsm NUMERIC(6,2),
    fabric_width NUMERIC(6,2),
    weight_kg NUMERIC(8,3) NOT NULL,
    meterage NUMERIC(8,2),
    status VARCHAR(3) NOT NULL DEFAULT 'in',
    rack_id INTEGER REFERENCES wms.warehouse_racks(id) ON UPDATE CASCADE ON DELETE SET NULL,
    defect_points INTEGER DEFAULT 0,
    quality_grade VARCHAR(20),
    shade_id INTEGER REFERENCES wms.shades(id) ON UPDATE CASCADE ON DELETE SET NULL,
    received_date TIMESTAMP,
    issued_date TIMESTAMP,
    supplier VARCHAR(100),
    remarks TEXT,
    CONSTRAINT ck_fabric_rolls_status CHECK (status IN ('in', 'out'))
);

